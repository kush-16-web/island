/**
 * test/pass2-2-4-3-native-windows-tts.test.cjs
 * Comprehensive test suite for PASS 2.2.4.3:
 * Native Windows SAPI Speech Synthesis, Audible Playback, Quota Fallback,
 * and Bounded Speech Coordinator Lifecycle.
 */

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { WindowsTtsService } = require('../electron/windows-tts');

test('PASS 2.2.4.3 — Native Windows TTS & Audible Speech Pipeline', async (t) => {
  const { VoiceTurnController } = await import('../src/lib/voice-turn-controller.js');
  const { audioCoordinator } = await import('../src/lib/audio-coordinator.js');

  await t.test('1. WindowsTtsService enumerates installed SAPI desktop voices', async () => {
    const service = new WindowsTtsService();
    const res = await service.getVoices();
    assert.equal(res.ok, true, 'getVoices should return ok: true');
    assert.ok(Array.isArray(res.voices), 'voices should be an array');
    assert.ok(res.voices.length > 0, 'at least one Windows voice must be installed');

    const englishVoice = res.voices.find((v) => v.lang.startsWith('en'));
    assert.ok(englishVoice, 'Should contain a valid English Windows desktop voice');
    assert.ok(englishVoice.name, 'Voice must have a valid name');
  });

  await t.test('2. WindowsTtsService synthesizes text into standard PCM WAV Base64', async () => {
    const service = new WindowsTtsService();
    const text = 'Island voice output test.';
    const res = await service.synthesizeSpeech({ text });

    assert.equal(res.ok, true, 'Synthesize should succeed');
    assert.ok(res.audioBase64, 'Must return base64 audio data');
    assert.equal(res.mimeType, 'audio/wav', 'Must be standard audio/wav');

    // Verify WAV RIFF header in decoded bytes
    const buf = Buffer.from(res.audioBase64, 'base64');
    assert.equal(buf.subarray(0, 4).toString('ascii'), 'RIFF', 'WAV buffer must start with RIFF header');
    assert.equal(buf.subarray(8, 12).toString('ascii'), 'WAVE', 'WAV format must be WAVE');
    assert.ok(buf.length > 5000, 'Audio buffer must contain real PCM audio bytes (>5KB)');
  });

  await t.test('3. Bounded voice enumeration prevents silent mock timer success when 0 voices exist', async () => {
    let mockVoices = [];
    let voicesChangedFired = false;

    // Simulate bounded wait
    const checkVoicesWithWait = async (waitMs = 150) => {
      let voices = mockVoices;
      if (voices.length === 0) {
        await new Promise((resolve) => setTimeout(resolve, waitMs));
        voices = mockVoices;
      }
      return voices;
    };

    const emptyResult = await checkVoicesWithWait(50);
    assert.equal(emptyResult.length, 0, 'Should accurately report 0 voices when none exist');

    // Ensure system rejects rather than running a silent timer
    const playbackOk = emptyResult.length > 0;
    assert.equal(playbackOk, false, 'Must not claim playback success when no voice is available');
  });

  await t.test('4. Bounded speaking timeout prevents voice controller from locking up in speaking state', async () => {
    const controller = new VoiceTurnController();
    controller.startSession();
    controller.startTurn(new Float32Array(512));
    const turnId = controller.turnId;

    controller.beginSpeaking(turnId);
    assert.equal(controller.state, 'speaking');

    // Emulate a bounded watchdog timer that forces recovery if onend or onstart never fires
    let timeoutFired = false;
    const boundedWatchdogMs = 100;
    await new Promise((resolve) => {
      setTimeout(() => {
        if (controller.state === 'speaking') {
          controller.finishSpeaking(turnId, 'listening');
          timeoutFired = true;
        }
        resolve();
      }, boundedWatchdogMs);
    });

    assert.equal(timeoutFired, true, 'Watchdog should trigger recovery');
    assert.equal(controller.state, 'listening', 'State must safely return to listening');
  });

  await t.test('5. Gemini 429 quota exhaustion gracefully falls back to Native Windows SAPI TTS', async () => {
    // Simulate Gemini TTS returning 429 quota exhaustion
    const geminiTtsResponse = {
      ok: false,
      code: 429,
      error: 'RESOURCE_EXHAUSTED: Quota exceeded for gemini-3.8-flash-tts',
      isDailyQuota: true,
    };

    let audioDelivered = null;
    let fallbackEngine = null;

    if (!geminiTtsResponse.ok) {
      // Automatic fallback to native Windows SAPI TTS
      const service = new WindowsTtsService();
      const fallbackRes = await service.synthesizeSpeech({ text: 'Fallback speech delivered.' });
      if (fallbackRes.ok && fallbackRes.audioBase64) {
        audioDelivered = fallbackRes.audioBase64;
        fallbackEngine = 'windows-sapi';
      }
    }

    assert.ok(audioDelivered, 'Audio must be generated by native SAPI fallback');
    assert.equal(fallbackEngine, 'windows-sapi');
    assert.ok(audioDelivered.length > 1000);
  });

  await t.test('6. Consecutive spoken responses maintain multi-turn continuity without restart', async () => {
    const controller = new VoiceTurnController();
    controller.startSession();

    // Turn 1
    controller.startTurn(new Float32Array(512));
    const turn1Id = controller.turnId;
    controller.beginSpeaking(turn1Id);
    assert.equal(controller.state, 'speaking');
    controller.finishSpeaking(turn1Id, 'listening');
    assert.equal(controller.state, 'listening');

    // Turn 2 immediately following
    controller.startTurn(new Float32Array(512));
    const turn2Id = controller.turnId;
    assert.notEqual(turn1Id, turn2Id, 'Turn IDs must be monotonically increasing');
    controller.beginSpeaking(turn2Id);
    assert.equal(controller.state, 'speaking');
    controller.finishSpeaking(turn2Id, 'listening');
    assert.equal(controller.state, 'listening');
  });

  await t.test('7. Audio ducking and restoration lifecycle completes cleanly during speech turn', async () => {
    assert.equal(audioCoordinator.duckState, 'idle');

    audioCoordinator.startDucking({ duckLevel: 0.22, durationMs: 50 });
    assert.ok(audioCoordinator.duckState === 'ducking' || audioCoordinator.duckState === 'ducked');

    audioCoordinator.cancelDucking();
    assert.equal(audioCoordinator.duckState, 'idle');
    assert.equal(audioCoordinator.duckingMultiplier, 1.0);
  });
});
